/**
 * ============================================================
 * 会话代次（sessionEpoch）
 * ============================================================
 * 认证会话的“代次号”：登录、登出、切账号、切服务器时 +1（见 AuthContext
 * 与 http.ts 的调用点）。每个请求在**发出时**捕获当时的代次，响应回来时
 * 只有代次仍一致才允许它改动本地凭证/身份状态：
 *
 *  - 迟到的续期 token（A 的响应在登出后才到）不会把凭证写回来；
 *  - 迟到的 401（A 的过期响应在 B 登录后才到）不会清掉 B 的 token 与缓存；
 *  - 迟到的 /auth/me 资料（A 的资料在 B 登录后才到）不会覆盖 B 的身份。
 *
 * 正常的**滑动续期不递增代次**（token 换新但会话没换），所以续期不受影响。
 * 这是“最终保护”：取消旧请求（AbortController 等）只是辅助手段，页面跳转、
 * 组件卸载路径很多，代次检查不依赖任何取消动作被正确执行。
 *
 * 只存在于内存（模块级计数器）：页面刷新后所有在途请求都会死掉，代次归零
 * 无影响；也不进 localStorage —— 它刻画的是“本次页面生命内的会话身份”，
 * 不是需要跨启动持久的状态。
 */

let epoch = 0;

/** 当前会话代次 */
export function currentSessionEpoch(): number {
  return epoch;
}

/**
 * 开启新会话代次（登录 / 登出 / 切账号 / 切服务器时调用）。
 * @returns 新代次号
 */
export function bumpSessionEpoch(): number {
  return ++epoch;
}

/** 仅测试用：隔离用例间的代次（业务代码不得调用） */
export function resetSessionEpochForTests(): void {
  epoch = 0;
}

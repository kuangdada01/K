/**
 * ============================================================
 * 无分页列表的硬上限（P1-8 / P2-34）
 * ============================================================
 * 收藏、转发、粉丝、关注、公告、评论这些列表**没有分页**：一次请求把该用户的
 * 全部相关行物化出来，而且每行还带 2 个 `COUNT(*)` + 1 个 `EXISTS` 子查询，
 * 全部跑在 better-sqlite3 的**同步**调用里 —— 期间整个 Node 事件循环停摆，
 * SSE 心跳、语音信令、所有人的普通请求一起卡住。
 *
 * 一条收藏 1 万条的账号，一个请求就能让整站卡顿；一个被大量关注的账号，
 * 粉丝列表同理。这不是「慢」，是**可用性**问题。
 *
 * 这里的做法是「硬上限 + has_more」而不是分页：
 * - 对老客户端**只增不改**：响应里多一个 `has_more` 字段，数组形状与字段都不变，
 *   默认语义在未超限时完全一致（不需要前端配合改 UI）；
 * - 代价：超过上限的账号会被截断（客户端目前不读 `has_more`，所以是静默的）。
 *   这是有意的取舍 —— 当前数据规模下（生产 34 篇帖子）离上限极远，
 *   而收益是把最坏情况从「整站卡死」压到「一次请求最多 500 行」。
 *
 * 真正的分页（keyset + 前端加载更多）需要在 UI 上加交互，属于契约/交互变更，
 * 已记在方案的待办里，等你确认后再做。
 * ============================================================
 */

/** 收藏/转发/粉丝/关注/公告列表的硬上限（一次请求最多返回多少行） */
export const HARD_LIST_CAP = 500;

/**
 * 单帖评论的硬上限。评论保留了「一次返回完整评论树」的既有语义
 * （老客户端的评论树依赖它），因此这里不改成默认分页，只封顶。
 */
export const HARD_COMMENT_CAP = 500;

/**
 * 按上限取行的通用辅助：多取一行用于精确判断 `has_more`，再切掉它。
 * 用 +1 而不是 `rows.length === cap` 判断，避免「恰好等于上限」时误报还有更多。
 */
export function capRows<T>(rows: T[], cap: number): { rows: T[]; has_more: boolean } {
  if (rows.length <= cap) return { rows, has_more: false };
  return { rows: rows.slice(0, cap), has_more: true };
}

/** SQL 里拼接 `LIMIT ?` 时用的取值：上限 + 1（用于探测是否还有更多） */
export function probeLimit(cap: number): number {
  return cap + 1;
}
